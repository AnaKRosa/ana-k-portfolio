#!/usr/bin/env node
/**
 * Regenerates the "From the blog" section on the homepage (index.html)
 * with the 3 most recent posts, combining:
 *   - every markdown post in src/posts/ (the CMS/Eleventy pipeline —
 *     picked up automatically, no manual edits needed as new posts
 *     are published through Decap CMS)
 *   - the older hand-written posts listed in legacy-posts.json
 *
 * Runs as part of the Netlify build (see netlify.toml), after Eleventy,
 * so index.html always reflects whatever is newest on every deploy.
 *
 * The block between the RECENT-POSTS:START / RECENT-POSTS:END comments
 * in index.html is fully owned by this script — don't hand-edit it,
 * edits will be overwritten on the next build.
 */
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const ROOT = path.join(__dirname, "..");
const POSTS_DIR = path.join(ROOT, "src/posts");
const LEGACY_PATH = path.join(ROOT, "legacy-posts.json");
const INDEX_PATH = path.join(ROOT, "index.html");
const START_MARKER = "<!-- RECENT-POSTS:START — auto-generated by scripts/build-recent-posts.js on every build, do not hand-edit -->";
const END_MARKER = "<!-- RECENT-POSTS:END -->";

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function loadLegacyPosts() {
  if (!fs.existsSync(LEGACY_PATH)) return [];
  const raw = JSON.parse(fs.readFileSync(LEGACY_PATH, "utf8"));
  return raw.map((p) => ({
    title: p.title,
    url: p.url,
    tag: p.tag,
    dateDisplay: p.dateDisplay,
    dateSort: new Date(p.dateSort),
    readTime: p.readTime,
    image: p.image,
    imageAlt: p.imageAlt || p.title,
  }));
}

function loadMarkdownPosts() {
  if (!fs.existsSync(POSTS_DIR)) return [];
  return fs
    .readdirSync(POSTS_DIR)
    .filter((f) => f.endsWith(".md"))
    .map((f) => {
      const slug = f.replace(/\.md$/, "");
      const { data } = matter(fs.readFileSync(path.join(POSTS_DIR, f), "utf8"));
      const image = (data.homeThumbnail || data.heroImage || "").replace(/^\//, "");
      const dateSort = new Date(data.postDate);
      return {
        title: data.title,
        url: `posts/${slug}/`,
        tag: data.tag,
        dateDisplay: data.postDate,
        dateSort: isNaN(dateSort) ? new Date() : dateSort,
        readTime: data.readTime,
        image,
        imageAlt: data.heroImageAlt || data.title,
      };
    });
}

function buildCardHtml(post, index) {
  const delayAttr = index === 0 ? "" : ` style="transition-delay:${(index * 0.1).toFixed(1)}s"`;
  return `    <a href="${escapeHtml(post.url)}" class="blog-card fade-up"${delayAttr}>
      <div class="blog-thumb"><img src="${escapeHtml(post.image)}" alt="${escapeHtml(post.imageAlt)}" style="width:100%;height:100%;object-fit:cover;display:block;" loading="lazy"></div>
      <span class="blog-tag">${escapeHtml(post.tag)}</span>
      <h3>${escapeHtml(post.title)}</h3>
      <span class="blog-meta">${escapeHtml(post.dateDisplay)} · ${escapeHtml(post.readTime)}</span>
    </a>`;
}

function main() {
  const posts = [...loadMarkdownPosts(), ...loadLegacyPosts()]
    .filter((p) => p.title && p.url)
    .sort((a, b) => b.dateSort - a.dateSort)
    .slice(0, 3);

  if (posts.length === 0) {
    console.warn("[build-recent-posts] No posts found — leaving index.html blog section untouched.");
    return;
  }

  const html = posts.map(buildCardHtml).join("\n");
  const block = `${START_MARKER}\n${html}\n    ${END_MARKER}`;

  const indexHtml = fs.readFileSync(INDEX_PATH, "utf8");
  const startIdx = indexHtml.indexOf(START_MARKER);
  const endIdx = indexHtml.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error("[build-recent-posts] RECENT-POSTS markers not found in index.html — aborting so nothing is silently skipped.");
  }
  const updated =
    indexHtml.slice(0, startIdx) + block + indexHtml.slice(endIdx + END_MARKER.length);

  fs.writeFileSync(INDEX_PATH, updated);
  console.log(`[build-recent-posts] Updated homepage with: ${posts.map((p) => p.title).join(" | ")}`);
}

main();
